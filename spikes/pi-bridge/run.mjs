import { spawn } from "node:child_process"; import http from "node:http";
import { chromium } from "/Users/admin/PWA-Knowledge-Podcast-OpenAI-TTS/node_modules/playwright-core/index.mjs";
const S = process.argv[2], PORT = 47891, TOKEN = "spike-" + Math.random().toString(36).slice(2);
const srv = http.createServer((q, r) => { r.setHeader("content-type", "text/html"); r.end("<title>page</title>"); });
await new Promise((ok) => srv.listen(0, "127.0.0.1", ok));
const origin = "http://127.0.0.1:" + srv.address().port;
const pi = spawn("pi", ["--mode", "rpc", "--no-session", "--offline", "--no-skills", "--no-prompt-templates", "--no-context-files", "-e", S + "/pi-spike/ext.ts"], { env: { ...process.env, PODCAST_BRIDGE_PORT: String(PORT), PODCAST_BRIDGE_TOKEN: TOKEN, PODCAST_BRIDGE_ORIGINS: origin }, cwd: S });
let buf = ""; const lines = [];
pi.stdout.on("data", (d) => { buf += d; let i; while ((i = buf.indexOf("\n")) >= 0) { lines.push(buf.slice(0, i)); buf = buf.slice(i + 1); } });
let err = ""; pi.stderr.on("data", (d) => (err += d));
const send = (o) => pi.stdin.write(JSON.stringify(o) + "\n");
const wait = (f, ms = 20000) => new Promise((ok, no) => { const t0 = Date.now(); const iv = setInterval(() => { const m = lines.find(f); if (m) { clearInterval(iv); ok(m); } else if (Date.now() - t0 > ms) { clearInterval(iv); no(new Error("timeout")); } }, 100); });
send({ id: "s", type: "get_state" });
console.log("get_state:", JSON.stringify(JSON.parse(await wait((l) => l.includes('"get_state"'))).success));
send({ id: "c", type: "get_commands" });
const cmds = JSON.parse(await wait((l) => l.includes('"get_commands"'))).data.commands.map((c) => c.name + ":" + c.source);
console.log("commands:", cmds.join(","));
const browser = await chromium.launch(); const page = await (await browser.newContext()).newPage();
await page.goto(origin);
const bad = await page.evaluate(async (u) => new Promise((res) => { const w = new WebSocket(u); w.onopen = () => res("OPEN"); w.onerror = () => res("REJECTED"); }), `ws://127.0.0.1:${PORT}/?token=wrong`);
console.log("wrong token:", bad);
await page.evaluate((u) => { window.ws = new WebSocket(u); window.ws.onmessage = (e) => { const m = JSON.parse(e.data); window.ws.send(JSON.stringify({ id: m.id, result: { pong: true, method: m.method, from: m.params.from, origin: location.origin } })); }; return new Promise((r) => (window.ws.onopen = r)); }, `ws://127.0.0.1:${PORT}/?token=${TOKEN}`);
console.log("page connected with token");
send({ id: "p", type: "prompt", message: "/podcast-ping" });
const note = await wait((l) => l.includes("extension_ui_request") && l.includes("page said"));
console.log("notify:", JSON.parse(note).message);
const pr = lines.find((l) => l.includes('"id":"p"') && l.includes('"response"')); console.log("prompt response:", pr?.slice(0, 160));
await browser.close(); pi.kill(); srv.close();
if (err.trim()) console.log("stderr:", err.slice(0, 300));
